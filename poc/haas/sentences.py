"""PoC の検証の音声に入れる表記のヒントの単語と文。

文の `{0}` を、合成の入力では読みに、正解の文では表記に置き換える。
"""

# 表記のヒントの単語（表記, 読み）。読みは Vocabulary の V1 と合成の入力に使用する
HINT_WORDS: list[tuple[str, str]] = [
    ("GitHub", "ギットハブ"),
    ("Claude", "クロード"),
    ("worktree", "ワークツリー"),
    ("WSL", "ダブリューエスエル"),
    ("Haas", "ハース"),
    ("冪等", "べきとう"),
    ("突合", "とつごう"),
    ("採番", "さいばん"),
    ("閾値", "しきいち"),
    ("改修", "かいしゅう"),
    ("疎通確認", "そつうかくにん"),
    ("名寄せ", "なよせ"),
]

# 1 文に表記のヒントの単語を 1 つ入れる（単語, 文の型）
SENTENCES: list[tuple[str, str]] = [
    ("GitHub", "変更を{0}へプッシュしてからレビューを頼みます。"),
    ("Claude", "{0}に設計書を読ませて差分をまとめてもらいました。"),
    ("worktree", "作業用の{0}を作ってからブランチを切り替えます。"),
    ("WSL", "{0}の中で文字起こしのサーバーを動かします。"),
    ("Haas", "{0}のモデルは日本語の音声認識に特化しています。"),
    ("冪等", "この処理は何度呼んでも結果が変わらない{0}な作りにします。"),
    ("突合", "請求データと入金データを月末に{0}します。"),
    ("採番", "新しい伝票は登録した順に{0}されます。"),
    ("閾値", "音量が{0}を下回ったら無音とみなします。"),
    ("改修", "古い画面を来月までに{0}する予定です。"),
    ("疎通確認", "本番の前に外部のサーバーとの{0}を済ませておきます。"),
    ("名寄せ", "重複した顧客の情報を{0}して一つにまとめます。"),
]


def reading_of(word: str) -> str:
    """表記のヒントの単語の読みを返す。"""
    return dict(HINT_WORDS)[word]


def render(index: int, *, for_synthesis: bool) -> str:
    """文を、合成の入力（読み）か正解の文（表記）にして返す。"""
    word, template = SENTENCES[index]
    return template.format(reading_of(word) if for_synthesis else word)
